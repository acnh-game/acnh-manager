#!/usr/bin/env python3
"""Build the desktop-forwarder NSP that ships inside ACNH-Manager.

The package has the same shape as the forwarder generated by the reference implementation:

  program NCA  exefs: main + main.npdm (the hbmenu loader)
               romfs: nextArgv + nextNroPath (the standard ACNH-Manager NRO)
  control NCA  romfs: control.nacp + icon_AmericanEnglish.dat
  meta NCA     PFS0: one Application CNMT

Only the three NCA headers are encrypted, with `header_key` from prod.keys.  Their file-system
sections remain plaintext, as they are for a homebrew forwarder: there is no ticket or title key.
The resulting NSP is a build input in data/ and is installed later without any key access.

This tool never prints key material.  `tools/build-forwarder.py` compiles the vendored
`sphaira/hbl` source in the pinned devkitPro container and passes the freshly produced
`main`/`main.npdm` here; no compiled loader binary is checked in.  The source revision and
hashes are recorded in the generated `data/forwarder_nsp_meta.bin`.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import pathlib
import struct


IVFC_MAX_LEVEL = 6
IVFC_HASH_BLOCK_SIZE = 0x4000
PFS0_EXEFS_HASH_BLOCK_SIZE = 0x10000
PFS0_META_HASH_BLOCK_SIZE = 0x1000
PFS0_PADDING_SIZE = 0x200
ROMFS_FILEPARTITION_OFS = 0x200
NCA_HEADER_SIZE = 0xC00
NCA_SECTION_SIZE = 0x200
ROMFS_ENTRY_EMPTY = 0xFFFFFFFF

FORWARDER_PREFIX = 0x0500000000000000
FORWARDER_MASK = 0x00FFFFFFFFFFF000
STANDARD_NRO_PATH = "sdmc:/switch/ACNH-Manager/ACNH-Manager.nro"
NCM_STORAGE_ID_SD = 5


def align(value: int, alignment: int) -> int:
    return (value + alignment - 1) & ~(alignment - 1)


def padding_size(offset: int, block: int) -> int:
    """Match the reference helper: advance to the next block even when already aligned."""
    return block - (offset % block)


def sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def load_parser_module() -> object:
    path = pathlib.Path(__file__).with_name("parse-nsp.py")
    spec = importlib.util.spec_from_file_location("acnh_parse_nsp", path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


PARSER = load_parser_module()


def read_keys(path: pathlib.Path) -> dict[str, bytes]:
    keys: dict[str, bytes] = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        try:
            keys[name.strip()] = bytes.fromhex(value.strip())
        except ValueError:
            continue
    return keys


def forwarder_title_id(nro_path: str, args: str = "") -> int:
    effective_args = nro_path if not args else f"{nro_path} {args}"
    digest = sha256((nro_path + effective_args).encode())
    head = int.from_bytes(digest[:8], "little")
    return FORWARDER_PREFIX | (head & FORWARDER_MASK)


def read_nro_assets(path: pathlib.Path) -> tuple[bytes, bytes]:
    data = path.read_bytes()
    if len(data) < 0x90:
        raise SystemExit(f"{path} is too short to be an NRO")
    code_size = struct.unpack_from("<I", data, 0x18)[0]
    if data[code_size : code_size + 4] != b"ASET":
        raise SystemExit(f"{path} has no ASET header")
    icon_off, icon_size, nacp_off, nacp_size = struct.unpack_from("<QQQQ", data, code_size + 8)
    icon = data[code_size + icon_off : code_size + icon_off + icon_size]
    nacp = data[code_size + nacp_off : code_size + nacp_off + nacp_size]
    if not icon or len(nacp) < 0x3070:
        raise SystemExit(f"{path} has incomplete NACP/icon assets")
    return nacp, icon


def read_nacp_assets(nacp_path: pathlib.Path, icon_path: pathlib.Path) -> tuple[bytes, bytes]:
    nacp = nacp_path.read_bytes()
    icon = icon_path.read_bytes()
    if not icon or len(nacp) < 0x3070:
        raise SystemExit("the NACP/icon assets are incomplete")
    return nacp, icon


def patch_nacp(nacp: bytes, title_id: int, version: str) -> bytes:
    out = bytearray(nacp)
    for language in range(16):
        base = language * 0x300
        out[base : base + 0x200] = b"\0" * 0x200
        out[base + 0x200 : base + 0x300] = b"\0" * 0x100
        out[base : base + len(b"ACNH-Manager")] = b"ACNH-Manager"
        out[base + 0x200 : base + 0x200 + len(b"acnh-game")] = b"acnh-game"

    out[0x3025] = 0
    out[0x3026] = 0
    out[0x3027] = 1
    struct.pack_into("<I", out, 0x3028, 0)
    out[0x3034] = 0
    out[0x3035] = 2
    out[0x3036] = 0
    out[0x3037] = 0
    struct.pack_into("<Q", out, 0x3038, title_id)
    out[0x3060 : 0x3070] = b"\0" * 0x10
    encoded = version.encode()
    if len(encoded) >= 0x10:
        raise SystemExit("the display version is too long for NACP")
    out[0x3060 : 0x3060 + len(encoded)] = encoded
    struct.pack_into("<Q", out, 0x3070, title_id ^ 0x1000)
    struct.pack_into("<Q", out, 0x3078, title_id)
    struct.pack_into("<Q", out, 0x3080, 0)
    struct.pack_into("<Q", out, 0x3088, 0)
    struct.pack_into("<Q", out, 0x3090, 0)
    struct.pack_into("<Q", out, 0x3098, 0)
    out[0x30A8 : 0x30B0] = b"acnh-mgr"
    for index in range(8):
        struct.pack_into("<Q", out, 0x30B0 + index * 8, title_id)
    out[0x30F0] = 2
    out[0x30F1] = 0
    struct.pack_into("<Q", out, 0x30F8, title_id)
    for offset in (0x3148, 0x3150, 0x3158, 0x3160):
        struct.pack_into("<Q", out, offset, 0)
    out[0x3213] = 0
    return bytes(out)


def patch_npdm(npdm: bytes, title_id: int) -> bytes:
    out = bytearray(npdm)
    if out[:4] != b"META":
        raise SystemExit("the loader NPDM does not start with META")
    aci0_offset, aci0_size, acid_offset, acid_size = struct.unpack_from("<IIII", out, 0x70)
    if (
        aci0_offset + aci0_size > len(out)
        or acid_offset + acid_size > len(out)
        or out[aci0_offset : aci0_offset + 4] != b"ACI0"
        or out[acid_offset + 0x200 : acid_offset + 0x204] != b"ACID"
    ):
        raise SystemExit("the loader NPDM has an unsupported ACI0/ACID layout")
    out[0x20:0x30] = b"Application".ljust(0x10, b"\0")
    out[0x30:0x40] = b"\0" * 0x10
    struct.pack_into("<Q", out, aci0_offset + 0x10, title_id)
    struct.pack_into("<Q", out, acid_offset + 0x210, title_id)
    struct.pack_into("<Q", out, acid_offset + 0x218, title_id)

    def patch_debug_capability(offset: int, size: int) -> None:
        pattern = 0xFFFF
        mask = 0x1FFFF
        value = 0x80000
        for at in range(offset, offset + size, 4):
            current = struct.unpack_from("<I", out, at)[0]
            if current & mask == pattern:
                struct.pack_into("<I", out, at, value | pattern)
                return

    aci0_kac_offset, aci0_kac_size = struct.unpack_from("<II", out, aci0_offset + 0x30)
    acid_kac_offset, acid_kac_size = struct.unpack_from("<II", out, acid_offset + 0x230)
    patch_debug_capability(aci0_offset + aci0_kac_offset, aci0_kac_size)
    patch_debug_capability(acid_offset + acid_kac_offset, acid_kac_size)
    return bytes(out)


def build_pfs0(entries: list[tuple[str, bytes]]) -> bytes:
    table = bytearray()
    names = bytearray()
    data = bytearray()
    for name, payload in entries:
        encoded = name.encode()
        table += struct.pack("<QQII", len(data), len(payload), len(names), 0)
        names += encoded + b"\0"
        data += payload
    names += b"\0" * ((-len(names)) & 0x1F)
    return struct.pack("<IIII", 0x30534650, len(entries), len(names), 0) + table + names + data


def pfs0_hash_table(pfs0: bytes, block_size: int) -> bytes:
    return b"".join(
        sha256(pfs0[offset : offset + block_size])
        for offset in range(0, len(pfs0), block_size)
    )


def romfs_hash_count(count: int) -> int:
    if count < 3:
        return 3
    if count < 19:
        return count | 1
    value = count
    primes = (2, 3, 5, 7, 11, 13, 17)
    while any(value % prime == 0 for prime in primes):
        value += 1
    return value


def romfs_path_hash(parent: int, path: bytes) -> int:
    value = parent ^ 123456789
    for byte in path:
        value = ((value >> 5) | ((value << 27) & 0xFFFFFFFF)) ^ byte
    return value & 0xFFFFFFFF


def build_romfs(entries: list[tuple[str, bytes]]) -> tuple[bytes, int]:
    names = [name[1:].encode() for name, _ in entries]
    file_table_size = sum(0x20 + align(len(name), 4) for name in names)
    dir_hash_count = romfs_hash_count(1)
    file_hash_count = romfs_hash_count(len(entries))
    dir_hash_size = dir_hash_count * 4
    file_hash_size = file_hash_count * 4
    dir_table_size = 0x18

    data_offsets: list[int] = []
    data_size = 0
    for _, payload in entries:
        data_size = align(data_size, 0x10)
        data_offsets.append(data_size)
        data_size += len(payload)

    dir_hash_offset = align(ROMFS_FILEPARTITION_OFS + data_size, 4)
    dir_table_offset = dir_hash_offset + dir_hash_size
    file_hash_offset = dir_table_offset + dir_table_size
    file_table_offset = file_hash_offset + file_hash_size
    total = file_table_offset + file_table_size
    image = bytearray(total)

    struct.pack_into(
        "<10Q",
        image,
        0,
        0x50,
        dir_hash_offset,
        dir_hash_size,
        dir_table_offset,
        dir_table_size,
        file_hash_offset,
        file_hash_size,
        file_table_offset,
        file_table_size,
        ROMFS_FILEPARTITION_OFS,
    )

    for (_, payload), offset in zip(entries, data_offsets):
        start = ROMFS_FILEPARTITION_OFS + offset
        image[start : start + len(payload)] = payload

    dir_hash = [ROMFS_ENTRY_EMPTY] * dir_hash_count
    root_hash = romfs_path_hash(0, b"")
    dir_hash[root_hash % dir_hash_count] = 0
    struct.pack_into(f"<{dir_hash_count}I", image, dir_hash_offset, *dir_hash)

    struct.pack_into(
        "<6I",
        image,
        dir_table_offset,
        0,
        ROMFS_ENTRY_EMPTY,
        ROMFS_ENTRY_EMPTY,
        0 if entries else ROMFS_ENTRY_EMPTY,
        ROMFS_ENTRY_EMPTY,
        0,
    )

    file_hash = [ROMFS_ENTRY_EMPTY] * file_hash_count
    file_entry_offset = file_table_offset
    for index, ((_, payload), name, data_offset) in enumerate(
        zip(entries, names, data_offsets)
    ):
        sibling = (
            file_entry_offset + 0x20 + align(len(name), 4) - file_table_offset
            if index + 1 < len(entries)
            else ROMFS_ENTRY_EMPTY
        )
        path_hash = romfs_path_hash(0, name)
        previous = file_hash[path_hash % file_hash_count]
        file_hash[path_hash % file_hash_count] = file_entry_offset - file_table_offset
        struct.pack_into(
            "<IIQQII",
            image,
            file_entry_offset,
            0,
            sibling,
            data_offset,
            len(payload),
            previous,
            len(name),
        )
        image[file_entry_offset + 0x20 : file_entry_offset + 0x20 + len(name)] = name
        file_entry_offset += 0x20 + align(len(name), 4)

    struct.pack_into(f"<{file_hash_count}I", image, file_hash_offset, *file_hash)
    del image[file_entry_offset:]
    # The reference reports buf.tell() after the complete RomFS.  Returning the file-data
    # partition length here truncates IVFC level 5 and makes the loader reject the title.
    return bytes(image), len(image)


def ivfc_create_level(source: bytes) -> bytes:
    table = b"".join(
        sha256(source[offset : offset + IVFC_HASH_BLOCK_SIZE])
        for offset in range(0, len(source), IVFC_HASH_BLOCK_SIZE)
    )
    return table + b"\0" * padding_size(len(table), IVFC_HASH_BLOCK_SIZE)


def set_section(header: bytearray, index: int, start: int, end: int) -> None:
    offset = 0x240 + index * 0x10
    struct.pack_into("<II", header, offset, start // 0x200, end // 0x200)
    header[offset + 8] = 0x01


def write_nca_pfs0(
    image: bytearray, header: bytearray, index: int, entries: list[tuple[str, bytes]],
    block_size: int
) -> None:
    pfs0 = build_pfs0(entries)
    table = pfs0_hash_table(pfs0, block_size)
    master = sha256(table)
    start = len(image)
    image += table
    image += b"\0" * padding_size(len(table), PFS0_PADDING_SIZE)
    pfs0_offset = len(image) - start
    image += pfs0
    image += b"\0" * padding_size(len(image), NCA_SECTION_SIZE)
    set_section(header, index, start, len(image))

    fs = 0x400 + index * 0x200
    struct.pack_into("<HBBBB", header, fs, 2, 1, 2, 1, 0)
    header[fs + 0x08 : fs + 0x28] = master
    struct.pack_into("<II", header, fs + 0x28, block_size, 2)
    struct.pack_into("<QQ", header, fs + 0x30, 0, len(table))
    struct.pack_into("<QQ", header, fs + 0x40, pfs0_offset, len(pfs0))
    header[0x280 + index * 0x20 : 0x2A0 + index * 0x20] = sha256(
        header[fs : fs + 0x200]
    )


def write_nca_romfs(
    image: bytearray, header: bytearray, index: int, entries: list[tuple[str, bytes]]
) -> None:
    romfs, content_size = build_romfs(entries)
    romfs += b"\0" * padding_size(len(romfs), IVFC_HASH_BLOCK_SIZE)
    levels = [b""] * IVFC_MAX_LEVEL
    levels[5] = romfs
    sizes = [0] * IVFC_MAX_LEVEL
    sizes[5] = content_size
    for level in range(4, -1, -1):
        levels[level] = ivfc_create_level(levels[level + 1])
        sizes[level] = len(levels[level])

    start = len(image)
    for level in levels:
        image += level
    image += b"\0" * padding_size(len(image), NCA_SECTION_SIZE)
    set_section(header, index, start, len(image))

    fs = 0x400 + index * 0x200
    struct.pack_into("<HBBBB", header, fs, 2, 0, 3, 1, 0)
    base = fs + 0x08
    struct.pack_into("<III", header, base, 0x43465649, 0x20000, 0x20)
    header[base + 0x0C] = 7
    logical = 0
    for level, size in enumerate(sizes):
        struct.pack_into("<QQII", header, base + 0x10 + level * 0x18, logical, size, 0x0E, 0)
        logical += size
    header[base + 0xC0 : base + 0xE0] = sha256(levels[0])
    header[0x280 + index * 0x20 : 0x2A0 + index * 0x20] = sha256(
        header[fs : fs + 0x200]
    )


def encrypt_nca_header(header: bytearray, header_key: bytes) -> bytes:
    data_round_keys = PARSER._expand_key(header_key[:16])
    tweak_round_keys = PARSER._expand_key(header_key[16:32])
    output = bytearray()
    for sector, position in enumerate(range(0, len(header), 0x200)):
        chunk = header[position : position + 0x200]
        tweak = PARSER._encrypt_block(
            tweak_round_keys, b"\0" * 8 + struct.pack(">Q", sector)
        )
        for block in range(0, len(chunk), 16):
            piece = bytes(a ^ b for a, b in zip(chunk[block : block + 16], tweak))
            output += bytes(
                a ^ b
                for a, b in zip(PARSER._encrypt_block(data_round_keys, piece), tweak)
            )
            tweak = PARSER._incr_tweak(tweak)
    return bytes(output)


def create_nca(
    title_id: int, header_key: bytes, content_type: int, sections: list[tuple[str, object]]
) -> tuple[bytes, bytes]:
    header = bytearray(NCA_HEADER_SIZE)
    image = bytearray(NCA_HEADER_SIZE)
    for index, (kind, payload) in enumerate(sections):
        if kind == "pfs0":
            entries, block_size = payload
            write_nca_pfs0(image, header, index, entries, block_size)
        elif kind == "romfs":
            write_nca_romfs(image, header, index, payload)
        else:
            raise AssertionError(kind)

    struct.pack_into("<I", header, 0x200, 0x3341434E)
    header[0x204] = 0
    header[0x205] = content_type
    header[0x206] = 0
    header[0x207] = 0
    struct.pack_into("<QQ", header, 0x208, len(image), title_id)
    struct.pack_into("<I", header, 0x21C, 0x000C1100)
    encrypted = encrypt_nca_header(header, header_key)
    image[:NCA_HEADER_SIZE] = encrypted
    return bytes(image), sha256(image)


def build_cnmt(title_id: int, program_hash: bytes, control_hash: bytes,
               program_size: int, control_size: int) -> bytes:
    cnmt = bytearray(0x20 + 0x10 + 2 * 0x38 + 0x20)
    struct.pack_into("<QI", cnmt, 0, title_id, 0)
    cnmt[0x0C] = 0x80
    struct.pack_into("<HHHBB", cnmt, 0x0E, 0x10, 2, 1, 0, NCM_STORAGE_ID_SD)
    cnmt[0x16] = 0
    struct.pack_into("<QII", cnmt, 0x20, title_id | 0x800, 0, 0)
    for index, (digest, size, kind) in enumerate(
        ((program_hash, program_size, 1), (control_hash, control_size, 3))
    ):
        offset = 0x30 + index * 0x38
        cnmt[offset : offset + 0x20] = digest
        info = offset + 0x20
        cnmt[info : info + 0x10] = digest[:0x10]
        struct.pack_into("<I", cnmt, info + 0x10, size & 0xFFFFFFFF)
        cnmt[info + 0x14] = (size >> 32) & 0xFF
        cnmt[info + 0x15] = 0
        cnmt[info + 0x16] = kind
        cnmt[info + 0x17] = 0
    return bytes(cnmt)


def build_forwarder(
    nacp: bytes, icon: bytes, loader_main: pathlib.Path, loader_npdm: pathlib.Path,
    keys_path: pathlib.Path, source_record: pathlib.Path | None = None
) -> tuple[bytes, dict[str, object]]:
    keys = read_keys(keys_path)
    header_key = keys.get("header_key")
    if header_key is None or len(header_key) != 0x20:
        raise SystemExit(f"header_key is missing from {keys_path}")

    title_id = forwarder_title_id(STANDARD_NRO_PATH)
    version_bytes = nacp[0x3060:0x3070].split(b"\0", 1)[0].decode()
    nacp = patch_nacp(nacp, title_id, version_bytes)
    npdm = patch_npdm(loader_npdm.read_bytes(), title_id)

    program, program_hash = create_nca(
        title_id,
        header_key,
        0,
        [
            (
                "pfs0",
                (
                    [
                        ("main", loader_main.read_bytes()),
                        ("main.npdm", npdm),
                    ],
                    PFS0_EXEFS_HASH_BLOCK_SIZE,
                ),
            ),
            (
                "romfs",
                [
                    ("/nextArgv", STANDARD_NRO_PATH.encode()),
                    ("/nextNroPath", STANDARD_NRO_PATH.encode()),
                ],
            ),
        ],
    )
    control, control_hash = create_nca(
        title_id,
        header_key,
        2,
        [
            (
                "romfs",
                [
                    ("/control.nacp", nacp),
                    ("/icon_AmericanEnglish.dat", icon),
                ],
            )
        ],
    )
    cnmt = build_cnmt(
        title_id, program_hash, control_hash, len(program), len(control)
    )
    meta, meta_hash = create_nca(
        title_id,
        header_key,
        1,
        [
            (
                "pfs0",
                (
                    [(f"Application_{title_id:016X}.cnmt", cnmt)],
                    PFS0_META_HASH_BLOCK_SIZE,
                ),
            )
        ],
    )

    nsp = build_pfs0(
        [
            (f"{meta_hash[:0x10].hex()}.cnmt.nca", meta),
            (f"{program_hash[:0x10].hex()}.nca", program),
            (f"{control_hash[:0x10].hex()}.nca", control),
        ]
    )
    metadata: dict[str, object] = {
        "titleId": f"{title_id:016x}",
        "displayVersion": version_bytes,
        "nroPath": STANDARD_NRO_PATH,
        "loaderProject": "sphaira/hbl",
        "loaderVersion": "3.0.0",
        "loaderCommit": "338348e74b6d278bc570a9be5373d25197bf6c8d",
        "loaderMainSha256": hashlib.sha256(loader_main.read_bytes()).hexdigest(),
        "loaderNpdmSha256": hashlib.sha256(loader_npdm.read_bytes()).hexdigest(),
        "nacpSha256": hashlib.sha256(nacp).hexdigest(),
        "iconSha256": hashlib.sha256(icon).hexdigest(),
        "programContentId": program_hash.hex(),
        "controlContentId": control_hash.hex(),
        "metaContentId": meta_hash.hex(),
        "nspSha256": hashlib.sha256(nsp).hexdigest(),
        "size": len(nsp),
    }
    if source_record is not None:
        metadata["loaderSource"] = json.loads(source_record.read_text())
    return nsp, metadata


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--nro", type=pathlib.Path)
    parser.add_argument("--nacp", type=pathlib.Path)
    parser.add_argument("--icon", type=pathlib.Path)
    parser.add_argument("--loader-main", type=pathlib.Path, required=True)
    parser.add_argument("--loader-npdm", type=pathlib.Path, required=True)
    parser.add_argument(
        "--keys", type=pathlib.Path,
        default=pathlib.Path("../../SDcard/switch/prod.keys")
    )
    parser.add_argument(
        "--source-record", type=pathlib.Path,
        help="optional SOURCE.json describing the checked-in loader source"
    )
    parser.add_argument("--output", type=pathlib.Path, required=True)
    parser.add_argument("--metadata", type=pathlib.Path, required=True)
    args = parser.parse_args()

    if args.nacp is not None or args.icon is not None:
        if args.nacp is None or args.icon is None:
            parser.error("--nacp and --icon must be used together")
        nacp, icon = read_nacp_assets(args.nacp, args.icon)
    else:
        nro = args.nro or pathlib.Path("acnh-manager.nro")
        nacp, icon = read_nro_assets(nro)
    nsp, metadata = build_forwarder(
        nacp, icon, args.loader_main, args.loader_npdm, args.keys, args.source_record
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(nsp)
    args.metadata.write_text(json.dumps(metadata, indent=2) + "\n")
    print(f"{args.output}: {len(nsp)} bytes")
    print(f"title id: 0x{int(metadata['titleId'], 16):016x}")
    print(f"sha256: {metadata['nspSha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
